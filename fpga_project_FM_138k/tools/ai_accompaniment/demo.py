"""Export paired auditions from actual V2 RTL output, not a separate policy simulator."""
import csv,argparse
from pathlib import Path
import mido
ROOT=Path(__file__).resolve().parents[2]
NAMES=['01_soft_legato','02_hard_legato','03_dense','04_F_major','05_C_minor','06_staccato']
def main():
    ap=argparse.ArgumentParser();ap.add_argument('--trace',default=str(ROOT/'tmp/ai_v2_pairs.csv'));args=ap.parse_args()
    rows=list(csv.DictReader(open(args.trace)));dst=ROOT/'assets/ai/v2';dst.mkdir(exist_ok=True)
    for case,name in enumerate(NAMES):
        rs=[r for r in rows if int(r['case'])==case];first=min(int(r['cycle']) for r in rs)
        midi=mido.MidiFile(ticks_per_beat=480)
        for ch,part in enumerate(['LIVE','BASS']):
            tr=mido.MidiTrack();midi.tracks.append(tr)
            tr.append(mido.MetaMessage('track_name',name=part+' '+name))
            if ch==0:tr.append(mido.MetaMessage('set_tempo',tempo=500000))
            tr.append(mido.Message('program_change',program=4 if ch==0 else 33,channel=ch))
            last=0
            for r in rs:
                if r['part']!=part:continue
                tick=round((int(r['cycle'])-first)*120/16000)
                status=int(r['status'],16)&0xf0;n=int(r['note']);v=int(r['velocity'])
                typ={0x90:'note_on',0x80:'note_off',0xb0:'control_change'}[status]
                msg=mido.Message(typ,channel=ch,time=tick-last,**({'control':n,'value':v} if typ=='control_change' else {'note':n,'velocity':v}))
                tr.append(msg);last=tick
        midi.save(str(dst/(name+'.mid')))
    (dst/'README.md').write_text('# V2 paired auditions\n\nGenerated by sim/tb_ai_bass_responsiveness.sv using actual RTL and trained INT8 weights.\nSix 4-bar paired cases at 120 BPM; General MIDI playback is not FPGA timbre.\nSoft/hard differ in input velocity, sparse/dense in onset rate, C/F in LH harmony, legato/staccato in key duration.\nReproduce: run RTL paired test, then python tools/ai_accompaniment/demo.py.\n')
    print('Exported six original LIVE+BASS RTL MIDI auditions to',dst)
if __name__=='__main__':main()
